export const OPERATIONS: OperationDef[] = RAW.map((op, index) => ({ ...op, index }));

export const OP_MAP: Map<string, OperationDef> = new Map(OPERATIONS.map((op) => [op.id, op]));

export const OP_ACH_THRESHOLDS = [1, 50, 100, 200, 300, 400, 500];

export function getOp(id: string): OperationDef {
  const op = OP_MAP.get(id);
  if (!op) throw new Error(`Unknown operation ${id}`);
  return op;
}
